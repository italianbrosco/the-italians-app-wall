grep -q 'No third-party analytics or advertising' "$TMP_DIR/abc-smash-privacy.html"
grep -q '<title>ABC Smash Support' "$TMP_DIR/abc-smash-support.html"
grep -q 'ciminillo@italianbrosco.com' "$TMP_DIR/abc-smash-support.html"
grep -q '<title>Are You Human? Privacy Policy' "$TMP_DIR/are-you-human-privacy.html"
