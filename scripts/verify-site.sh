curl -fsSL "$BASE_URL/blackwake-21/support/" -o "$TMP_DIR/blackwake-21-support.html"
curl -fsSL "$BASE_URL/dont-touch-red/privacy/" -o "$TMP_DIR/dont-touch-red-privacy.html"
